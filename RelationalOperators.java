public class RelationalOperators 
{
    public static void main(String[] args) 
{
        
        
        int a = 67;
        int b = 37;
System.out.println("Values: a ="+ a +", b=" + b);

            // 1. Equal to (==)
        System.out.println("a == b: " + (a == b));

        // 2. Not Equal to (!=)
        System.out.println("a != b: " + (a != b));

        // 3. Greater than (>)
        System.out.println("a > b: " + (a > b));

        // 4. Less than (<)
        System.out.println("a < b:" + (a < b));

        // 5. Greater than or Equal to (>=)
        System.out.println("a >= b :" + (a >= b));

        // 6. Less than or Equal to (<=)
        System.out.println("a <= b :" + (a <= b));
    }
}